// The error boundary for the database layer (CLAUDE.md, "Database", HARD RULE).
//
// Every error from `pg` or the network stack goes through toDbError() and comes
// out as a DbError. A DbError carries a KIND, an optional FIELD, a fixed MESSAGE
// and an error ID. All four come from constants in this file and
// dbConstraints.ts or from the app's own random id: NOTHING is copied from the
// raw error into a DbError or into a log line.
//
// Two lists, and they are different:
//  - NEVER OUT, NEVER LOGGED: the raw error object, its message, detail, hint,
//    where, column, schema, and the host, address or user a network error
//    carries. Any of them can contain the failing row or the connection string.
//    This file READS message (to tell a timeout from a dropped connection) and
//    column (to find a NOT NULL rule). It never stores or logs either.
//  - SAFE TO LOG, NEVER RETURNED: SQLSTATE, constraint name, table name and the
//    error id; and, for SQLSTATE 42P01 (undefined_table) ONLY, the name of the
//    relation that does not exist (see relationOf below). Each is checked against
//    a strict pattern before it is logged, so an odd value cannot smuggle text
//    into a log line.
//
// No `cause` is attached to a DbError: a cause would carry the raw error along.
//
// Pure on purpose: no pg import, no window guard, no I/O but the injectable log.
// Relative imports with .ts extensions: Node's test runner loads this directly.
import { randomUUID } from "node:crypto";
import { CONSTRAINT_RULES, NOT_NULL_RULES } from "./dbConstraints.ts";

export type DbErrorKind =
  // The person typed or chose something the database refuses. A form screen.
  | "unique"
  | "foreign_key"
  | "check"
  | "not_null"
  | "malformed" // a value in the wrong format (for example a bad id in a URL)
  // The database could not do the work. An error screen, not a form screen.
  | "unavailable" // unreachable, out of connections, refused or dropped
  | "timeout"
  | "retryable" // a deadlock or serialization failure; the same action may succeed
  | "config" // DATABASE_URL missing or unusable; nothing was sent
  | "restricted" // a protected row (append-only) refused the change
  | "unexpected"; // anything else, including a constraint nobody mapped

/** What a person did wrong, as opposed to the database being unable to work. */
export const DB_INPUT_KINDS: ReadonlySet<DbErrorKind> = new Set<DbErrorKind>([
  "unique",
  "foreign_key",
  "check",
  "not_null",
  "malformed",
]);

export const DB_ERROR_MESSAGES: Readonly<Record<Exclude<DbErrorKind, "unique" | "foreign_key" | "check" | "not_null">, string>> =
  Object.freeze({
    malformed: "A value was not in the expected format.",
    unavailable: "The database cannot be reached right now. Please try again in a moment.",
    timeout: "The database took too long to respond. Please try again.",
    retryable: "Another change happened at the same time. Please try again.",
    config: "The database is not set up for this application.",
    restricted: "This record cannot be changed or deleted.",
    unexpected: "Something went wrong. Please try again, and quote the reference if it keeps happening.",
  });

export class DbError extends Error {
  readonly kind: DbErrorKind;
  /** Generated by the app for this occurrence. Quote it; look it up in the log. */
  readonly errorId: string;
  /** The form field the message belongs to, from the mapping table; null if none. */
  readonly field: string | null;

  constructor(kind: DbErrorKind, message: string, errorId: string, field: string | null = null) {
    super(message);
    this.name = "DbError";
    this.kind = kind;
    this.errorId = errorId;
    this.field = field;
  }
}

export function isDbError(value: unknown): value is DbError {
  return value instanceof DbError;
}

/** True when a person can fix it by changing what they entered. False means infrastructure or a defect. */
export function isInputError(value: unknown): value is DbError {
  return value instanceof DbError && DB_INPUT_KINDS.has(value.kind);
}

/** What is logged for an error. Exactly these keys, never more. */
export interface DbErrorLogEntry {
  event: "db_error";
  errorId: string;
  kind: DbErrorKind;
  sqlstate?: string;
  constraint?: string;
  table?: string;
  /** 42P01 only: the relation that does not exist, as named in OUR SQL ("staff", "public.staff"). */
  relation?: string;
}

export interface ToDbErrorOptions {
  /** Receives the one log entry. Default: one JSON line on console.error. */
  log?: (entry: DbErrorLogEntry) => void;
  /** Default: a short random id. Tests inject a fixed one. */
  newId?: () => string;
}

export function newErrorId(): string {
  // Random, not derived from anything about the error.
  return `E-${randomUUID().replace(/-/g, "").slice(0, 10).toUpperCase()}`;
}

function defaultLog(entry: DbErrorLogEntry): void {
  console.error(JSON.stringify(entry));
}

// Node network and socket error codes. Several are five uppercase letters (EPIPE),
// which would look like a SQLSTATE, so these are checked first.
const NETWORK_CODES: ReadonlySet<string> = new Set([
  "ECONNREFUSED",
  "ECONNRESET",
  "ECONNABORTED",
  "ENOTFOUND",
  "EAI_AGAIN",
  "EHOSTUNREACH",
  "ENETUNREACH",
  "ENETDOWN",
  "EPIPE",
  "ENOENT", // a Unix socket path that does not exist
]);
const NETWORK_TIMEOUT_CODES: ReadonlySet<string> = new Set(["ETIMEDOUT", "ESOCKETTIMEDOUT"]);

const SQLSTATE = /^[0-9A-Z]{5}$/;
const IDENTIFIER = /^[A-Za-z0-9_]{1,63}$/;
/** A relation name, optionally schema-qualified: identifiers and one dot, nothing else. */
const RELATION = /^[A-Za-z0-9_]{1,63}(\.[A-Za-z0-9_]{1,63})?$/;

// SQLSTATE 42P01, undefined_table. PostgreSQL does not fill the `table` field for it: the name
// is ONLY in the message, in one of these fixed forms (English server messages):
//   relation "staff" does not exist
//   missing FROM-clause entry for table "r"
// WHY THIS IS SAFE TO LOG when `message` in general is not: for this error the only variable
// part of the message is a relation name exactly as it is written in the SQL TEXT, and every
// SQL text in CSS is a literal in our own source (the sql tag makes every value a parameter, so
// no visitor, client or staff data can ever be in a name). It is a schema identifier we chose,
// like a constraint name. Only the quoted name is taken, only for 42P01, and only if it is a
// bare identifier (optionally schema.name); anything else, or a message in another language,
// logs no relation at all. The rest of the message is never stored or logged.
const UNDEFINED_TABLE_TEXT = [/^relation "([^"]{1,130})" does not exist$/, /^missing FROM-clause entry for table "([^"]{1,130})"$/];

function relationOf(sqlstate: string | undefined, text: string): string | undefined {
  if (sqlstate !== "42P01") return undefined;
  for (const pattern of UNDEFINED_TABLE_TEXT) {
    const name = pattern.exec(text)?.[1];
    if (name !== undefined && RELATION.test(name)) return name;
  }
  return undefined;
}

// Text the pg client and pool produce with NO code. Matched for classification
// only; the text is never stored, logged or returned.
const TIMEOUT_TEXT = /timeout|timed out/i;
const DROPPED_TEXT =
  /connection terminated|not queryable|connection error|after calling end|server closed the connection|ended unexpectedly/i;
const CONFIG_TEXT = /sasl|scram|password must be a string|invalid connection string|invalid url/i;

interface RawFacts {
  code: string | undefined;
  constraint: string | undefined;
  table: string | undefined;
  column: string | undefined;
  /** For classification only. Never stored, never logged. */
  text: string;
}

function readString(source: Record<string, unknown>, key: string): string | undefined {
  const value = source[key];
  return typeof value === "string" ? value : undefined;
}

function readFacts(raw: unknown): RawFacts {
  if (typeof raw !== "object" || raw === null) {
    return { code: undefined, constraint: undefined, table: undefined, column: undefined, text: "" };
  }
  const source = raw as Record<string, unknown>;
  return {
    code: readString(source, "code"),
    constraint: readString(source, "constraint"),
    table: readString(source, "table"),
    column: readString(source, "column"),
    text: readString(source, "message") ?? "",
  };
}

interface Classification {
  kind: DbErrorKind;
  message: string;
  field: string | null;
}

function generic(kind: Exclude<DbErrorKind, "unique" | "foreign_key" | "check" | "not_null">): Classification {
  return { kind, message: DB_ERROR_MESSAGES[kind], field: null };
}

function classifySqlstate(sqlstate: string, facts: RawFacts): Classification {
  const klass = sqlstate.slice(0, 2);

  // Integrity violations: mapped by constraint name, or by table.column for NOT NULL.
  if (sqlstate === "23505" || sqlstate === "23503" || sqlstate === "23514") {
    const expected = sqlstate === "23505" ? "unique" : sqlstate === "23503" ? "foreign_key" : "check";
    const found = facts.constraint === undefined ? undefined : CONSTRAINT_RULES[facts.constraint];
    // A rule only applies to the kind of violation it was written for.
    if (found !== undefined && found.kind === expected) {
      return { kind: found.kind, message: found.message, field: found.field };
    }
    return generic("unexpected");
  }
  if (sqlstate === "23502") {
    const key = facts.table !== undefined && facts.column !== undefined ? `${facts.table}.${facts.column}` : undefined;
    const found = key === undefined ? undefined : NOT_NULL_RULES[key];
    if (found !== undefined) return { kind: "not_null", message: found.message, field: found.field };
    return generic("unexpected");
  }
  if (sqlstate === "23001") return generic("restricted"); // restrict_violation: our append-only triggers

  if (klass === "22") return generic("malformed"); // data exception: bad uuid, too long, out of range
  if (sqlstate === "40001" || sqlstate === "40P01" || sqlstate === "55P03") return generic("retryable");
  if (sqlstate === "57014" || sqlstate === "25P03") return generic("timeout"); // statement / idle-in-transaction timeout
  if (
    klass === "08" || // connection exception
    klass === "53" || // insufficient resources, including too_many_connections 53300
    klass === "28" || // invalid authorization
    klass === "58" || // system error
    sqlstate === "57P01" ||
    sqlstate === "57P02" ||
    sqlstate === "57P03" ||
    sqlstate === "3D000"
  ) {
    return generic("unavailable");
  }
  return generic("unexpected");
}

function classify(facts: RawFacts): { result: Classification; sqlstate: string | undefined } {
  const code = facts.code;

  if (code !== undefined && NETWORK_TIMEOUT_CODES.has(code)) return { result: generic("timeout"), sqlstate: undefined };
  if (code !== undefined && NETWORK_CODES.has(code)) return { result: generic("unavailable"), sqlstate: undefined };

  if (code !== undefined && SQLSTATE.test(code)) {
    return { result: classifySqlstate(code, facts), sqlstate: code };
  }

  // No usable code: pg's own client and pool errors (a timeout, a dropped
  // connection, a malformed connection string). Order matters: "Connection
  // terminated due to connection timeout" is a timeout, not just a drop.
  if (TIMEOUT_TEXT.test(facts.text)) return { result: generic("timeout"), sqlstate: undefined };
  if (CONFIG_TEXT.test(facts.text)) return { result: generic("config"), sqlstate: undefined };
  if (DROPPED_TEXT.test(facts.text)) return { result: generic("unavailable"), sqlstate: undefined };
  return { result: generic("unexpected"), sqlstate: undefined };
}

/**
 * Turns anything thrown by pg, the pool or the network into a DbError, logs the
 * safe facts once, and returns it. A DbError passed in is returned unchanged (it
 * has already been logged).
 */
export function toDbError(raw: unknown, options: ToDbErrorOptions = {}): DbError {
  if (raw instanceof DbError) return raw;

  const log = options.log ?? defaultLog;
  const errorId = (options.newId ?? newErrorId)();
  const facts = readFacts(raw);
  const { result, sqlstate } = classify(facts);

  const entry: DbErrorLogEntry = { event: "db_error", errorId, kind: result.kind };
  if (sqlstate !== undefined) entry.sqlstate = sqlstate;
  if (facts.constraint !== undefined && IDENTIFIER.test(facts.constraint)) entry.constraint = facts.constraint;
  if (facts.table !== undefined && IDENTIFIER.test(facts.table)) entry.table = facts.table;
  const relation = relationOf(sqlstate, facts.text);
  if (relation !== undefined) entry.relation = relation;

  try {
    log(entry);
  } catch {
    // A failing logger must never replace the error being reported.
  }
  return new DbError(result.kind, result.message, errorId, result.field);
}

/** For failures that are the application's own (not from pg): same shape, same log. */
export function appDbError(
  kind: Extract<DbErrorKind, "config" | "unexpected">,
  options: ToDbErrorOptions = {},
): DbError {
  const log = options.log ?? defaultLog;
  const errorId = (options.newId ?? newErrorId)();
  try {
    log({ event: "db_error", errorId, kind });
  } catch {
    // see above
  }
  return new DbError(kind, DB_ERROR_MESSAGES[kind], errorId, null);
}
